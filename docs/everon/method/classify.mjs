export function typeOf(p){
  const t=(re)=>re.test(p);
  if(t(/Structures\/Houses\/Town\//))return "townhouse";
  if(t(/Villa_E_2I01_Police/))return "police";
  if(t(/Structures\/Houses\/Villa\//))return "villa";
  if(t(/Structures\/Houses\/Garage\/|HouseAddon_Garage|Industrial\/Garages|Workshop_0|Warehouse_01_Workshop|Repair\//))return "garage";
  if(t(/Houses\/Shed\/|HouseAddon_Shed_E|Houses\/Village\/HouseAddon_Workshop/))return "shed";
  if(t(/Structures\/Houses\/(Village|Wooden|Prefabricated)\//))return "house";
  if(t(/Houses\/Farm\//))return "farmhouse";
  if(t(/Commercial\/Shops\//))return "shop";
  if(t(/Commercial\/Pubs\//))return "pub";
  if(t(/Commercial\/Booth\//))return "kiosk";
  if(t(/Commercial\/FuelStations\//))return "fuel";
  if(t(/Cultural\/Churches\//))return "church";
  if(t(/Cultural\/Chapels\//))return "chapel";
  if(t(/Cultural\/Castles\//))return "castle";
  if(t(/Services\/Hotels\//))return "hotel";
  if(t(/Services\/Government\//))return "government";
  if(t(/Services\/Fire\//))return "fire";
  if(t(/Agriculture\/(Barn|CowShed|Hayloft|WeightStation)/))return "farm";
  if(t(/Agriculture\/(Henhouse|Greenhouse)/))return "farm-small";
  if(t(/Industrial\/(Houses|Sheds)\/|Industrial\/Houses\//))return "industrial";
  if(t(/Industrial\/Containers\//))return "industrial-tank";
  if(t(/Industrial\/(Smokestacks|Towers)/))return "industrial-tower";
  if(t(/Military\//))return "military";
  if(t(/Airport\/(ControlTower|Hangar|Antenna)/))return "airport";
  if(t(/Infrastructure\/Naval\//))return "port";
  if(t(/Recreation\//))return "recreation";
  if(t(/Ruins\//))return "ruin";
  if(t(/Infrastructure\/Waterworks/))return "waterworks";
  return null;
}
