// tools/map/rules/cluster.mjs
//
// The map POI layer's min-zoom and cluster rules as pure functions (docs/architecture/everon-map.md section 1,
// card M4). Twin of LF_MapClusterRules in addons/LifeFramework/Scripts/Game/Feature/Map/LF_MapPlacesUI.c: both run
// the one case table addons/LifeFramework/Configs/Map/Rules/cluster.cases.json (loader: tools/map/rules/index.mjs),
// so they cannot drift.
// red-proof: tools/validation/map-cluster-selftest.mjs breaks a case and the table fails.
//
//   node tools/map/rules/cluster.mjs            run the case table (exit 1 on a mismatch or a stale Enforce copy)
//   node tools/map/rules/cluster.mjs --gen      write the Enforce copy of the table (LF_MapClusterCases.generated.c)
//
// Exports
//   evaluate(input)            the rule the case table runs: { op, zoom, minZoom, points } -> string
//   showAtZoom(zoom, minZoom)  a kind row's min zoom against the view zoom
//   isSolo(zoom)               at this zoom and closer every point is a single icon
//   cellSize(zoom)             the bucket size in metres
//   build(points, zoom)        [{ ids, x, z }]: what the layer draws, in first-member order (the emulator's call)
//
// Zoom is the emulator's and map-shots': the view is 12800 m / 2^zoom wide (zoom 0 is the island).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const rule = "cluster";
export const CASES_PATH = "addons/LifeFramework/Configs/Map/Rules/cluster.cases.json";
export const GENERATED_PATH = "addons/LifeFramework/Scripts/Game/Feature/Map/LF_MapClusterCases.generated.c";
export const WORLD_M = 12800; // lf-fixed: Everon's map width, the unit of zoom
export const SOLO_ZOOM = 4; // from here on every point is its own icon
export const CELLS = 8; // the bucket is this fraction of the view width
const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..", "..", "..");

export const showAtZoom = (zoom, minZoom) => minZoom <= zoom + 1e-6;
export const isSolo = (zoom) => zoom >= SOLO_ZOOM - 1e-6;
export const cellSize = (zoom) => WORLD_M / 2 ** zoom / CELLS;

/** points: [{ id, x, z, minZoom }] in place order. Returns [{ ids: [id], x, z }] in first-member order. */
export function build(points, zoom) {
  const shown = points.filter((p) => showAtZoom(zoom, p.minZoom ?? 0));
  if (isSolo(zoom)) return shown.map((p) => ({ ids: [p.id], x: p.x, z: p.z }));
  const cell = cellSize(zoom);
  const groups = [];
  const byCell = new Map();
  for (const p of shown) {
    const key = `${Math.floor(p.x / cell)},${Math.floor(p.z / cell)}`;
    let g = byCell.get(key);
    if (!g) {
      g = { ids: [], sx: 0, sz: 0 };
      byCell.set(key, g);
      groups.push(g);
    }
    g.ids.push(p.id);
    g.sx += p.x;
    g.sz += p.z;
  }
  return groups.map((g) => ({ ids: g.ids, x: g.sx / g.ids.length, z: g.sz / g.ids.length }));
}

export function parsePoints(text) {
  return String(text ?? "")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      const [id, x, z, minZoom] = s.split(":");
      return { id, x: Number(x), z: Number(z), minZoom: Number(minZoom ?? 0) };
    });
}

/** The rule the case table runs. */
export function evaluate({ op, zoom, minZoom = 0, points = "" }) {
  if (op === "minzoom") return showAtZoom(zoom, minZoom) ? "show" : "hide";
  if (op === "mode") return isSolo(zoom) ? "solo" : "clustered";
  if (op === "cluster") return build(parsePoints(points), zoom).map((g) => g.ids.join("+")).join(",");
  return `unknown op ${op}`;
}

/** Runs a parsed case table. Returns the failure messages (empty when every case passes). */
export function runCases(table) {
  const fails = [];
  for (const c of table.cases ?? []) {
    const got = evaluate(c.input);
    if (got !== c.expect) fails.push(`case "${c.name}": expected "${c.expect}", got "${got}"`);
  }
  return fails;
}

/** The Enforce copy of the case table (the engine cannot open the loose .json of an addon). */
export function generatedSource(root = ROOT) {
  const NL = String.fromCharCode(10);
  const BS = String.fromCharCode(92);
  const TAB = String.fromCharCode(9);
  const lines = readFileSync(join(root, CASES_PATH), "utf8").split(NL);
  while (lines.length && lines[lines.length - 1] === "") lines.pop();
  const q = (s) => s.split(BS).join(BS + BS).split('"').join(BS + '"');
  return [
    "// GENERATED by tools/map/rules/cluster.mjs --gen from Configs/Map/Rules/cluster.cases.json. Do not edit.",
    "//! The cluster case table as lines, for LF_Test_MapPlacesLayout (the engine cannot read the loose .json).",
    "class LF_MapClusterCasesData",
    "{",
    TAB + "//------------------------------------------------------------------------------------------------",
    TAB + "static string Json()",
    TAB + "{",
    TAB + TAB + "string text;",
    ...lines.map((l) => TAB + TAB + 'text += "' + q(l) + BS + 'n";'),
    TAB + TAB + "return text;",
    TAB + "}",
    "}",
    "",
  ].join(NL);
}

export function generatedIsCurrent(root = ROOT) {
  const f = join(root, GENERATED_PATH);
  return existsSync(f) && readFileSync(f, "utf8") === generatedSource(root);
}

export function loadCases(root = ROOT) {
  return JSON.parse(readFileSync(join(root, CASES_PATH), "utf8"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--gen")) {
    writeFileSync(join(ROOT, GENERATED_PATH), generatedSource());
    console.log(`cluster: wrote ${GENERATED_PATH}`);
    process.exit(0);
  }
  const table = loadCases();
  const fails = runCases(table);
  if (!generatedIsCurrent()) fails.push(`${GENERATED_PATH} is out of date: run node tools/map/rules/cluster.mjs --gen`);
  for (const f of fails) console.error(`FAIL ${f}`);
  if (fails.length) process.exit(1);
  console.log(`cluster: ok (${table.cases.length} cases)`);
}
