// tools/map/rules/discovery.mjs
//
// The map's discovery rule as a pure function (docs/architecture/everon-map.md section 4, card M13).
// Twin of LF_MapKnownRules in addons/LifeFramework/Scripts/Game/Feature/Map/LF_MapKnown.c: both run the one
// case table addons/LifeFramework/Configs/Map/Rules/discovery.cases.json (loader: tools/map/rules/index.mjs),
// so they cannot drift.
// red-proof: `node tools/map/rules/discovery.mjs` also runs the table with the slack set to 0 and fails
// unless that breaks a case, so a table that stopped testing the range would be caught.
//
//   node tools/map/rules/discovery.mjs            run the case table (exit 1 on a mismatch or a stale Enforce copy)
//   node tools/map/rules/discovery.mjs --gen      write the Enforce copy of the table (LF_MapKnownCases.generated.c)
//
// Exports
//   evaluate(input)        the rule: { action, known, live, distance, radius, recent } ->
//                          "visited" | "heard" | "kept" | "refused:rate" | "refused:dark" | "refused:range"
//   known(poi, persona)    what the emulator calls for `map render --as known`: the known state a persona
//                          holds of a POI row (none | heard | visited), after walking the persona's history
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const rule = "discovery";
export const CASES_PATH = "addons/LifeFramework/Configs/Map/Rules/discovery.cases.json";
export const GENERATED_PATH = "addons/LifeFramework/Scripts/Game/Feature/Map/LF_MapKnownCases.generated.c";
const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..", "..", "..");

// Mirrors LF_MapKnownRules (everon-map.md section 4, "How a visit is recorded").
export const DEFAULT_RADIUS = 20;
export const SLACK = 10;
export const ASKS_PER_MINUTE = 5;

/** The rule. `slack` is a parameter only so the self-check can break it. */
export function evaluate({ action, known = "none", live, distance = 0, radius = 0, recent = 0 }, slack = SLACK) {
  if (action === "hear") return known === "none" ? "heard" : "kept";
  if (recent >= ASKS_PER_MINUTE) return "refused:rate";
  if (!live) return "refused:dark";
  const r = radius > 0 ? radius : DEFAULT_RADIUS;
  if (distance > r + slack) return "refused:range";
  return known === "visited" ? "kept" : "visited";
}

/**
 * The emulator's personas (tools/map/rules/visibility.mjs audienceOf): `known` has walked the whole island,
 * `police` knows the town, `org:<id>` heard of the district, `new` heard only what the clerk marked
 * (poi.heardOf). Each is replayed through evaluate(), so `--as known` draws what the rule allows.
 */
export function known(poi, persona = "new") {
  const who = String(persona).split(":")[0];
  let state = "none";
  const step = (input) => {
    const out = evaluate({ known: state, live: poi.live ?? true, ...input });
    if (out === "visited" || out === "heard") state = out;
  };
  if (who === "known" || who === "police") step({ action: "visit", distance: 0 });
  else if (who === "org" || poi.heardOf) step({ action: "hear" });
  return state;
}

/** Runs a parsed case table. Returns the failure messages (empty when every case passes). */
export function runCases(table, slack = SLACK) {
  const fails = [];
  for (const c of table.cases ?? []) {
    const got = evaluate(c.input, slack);
    if (got !== c.expect) fails.push(`case "${c.name}": expected ${c.expect}, got ${got}`);
  }
  return fails;
}

/** The Enforce copy of the case table (the engine cannot read an addon's loose .json). */
export function generatedSource(root = ROOT) {
  const NL = String.fromCharCode(10);
  const BS = String.fromCharCode(92);
  const TAB = String.fromCharCode(9);
  const lines = readFileSync(join(root, CASES_PATH), "utf8").split(NL);
  while (lines.length && lines[lines.length - 1] === "") lines.pop();
  const q = (s) => s.split(BS).join(BS + BS).split('"').join(BS + '"');
  return [
    "// GENERATED by tools/map/rules/discovery.mjs --gen from Configs/Map/Rules/discovery.cases.json. Do not edit.",
    "//! The discovery case table as lines, for LF_Test_MapKnown (the engine cannot read the loose .json).",
    "class LF_MapKnownCasesData",
    "{",
    TAB + "//------------------------------------------------------------------------------------------------",
    TAB + "static string Json()",
    TAB + "{",
    TAB + TAB + "string text;",
    ...lines.map((l) => TAB + TAB + 'text += "' + q(l) + BS + 'n";'),
    TAB + TAB + "return text;",
    TAB + "}",
    "}",
    "",
  ].join(NL);
}

export function generatedIsCurrent(root = ROOT) {
  const f = join(root, GENERATED_PATH);
  return existsSync(f) && readFileSync(f, "utf8") === generatedSource(root);
}

export function loadCases(root = ROOT) {
  return JSON.parse(readFileSync(join(root, CASES_PATH), "utf8"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--gen")) {
    writeFileSync(join(ROOT, GENERATED_PATH), generatedSource());
    console.log(`discovery: wrote ${GENERATED_PATH}`);
    process.exit(0);
  }
  const table = loadCases();
  const fails = runCases(table);
  if (!generatedIsCurrent()) fails.push(`${GENERATED_PATH} is out of date: run node tools/map/rules/discovery.mjs --gen`);
  if (runCases(table, 0).length === 0) fails.push("red: the table still passes with no range slack; it must test the range");
  if (known({ live: true }, "known") !== "visited" || known({ live: true }, "new") !== "none" || known({ live: true, heardOf: true }, "new") !== "heard")
    fails.push("personas: known/new/heardOf must give visited/none/heard");
  for (const f of fails) console.error(`FAIL ${f}`);
  if (fails.length) process.exit(1);
  console.log(`discovery: ok (${table.cases.length} cases)`);
}
