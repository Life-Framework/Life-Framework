// tools/map/rules/shares.mjs
//
// The shared-mark rules as pure functions (docs/architecture/everon-map.md section 3, "Shared marks", card M9).
// Twin of LF_MapShareRules in addons/LifeFramework/Scripts/Game/Feature/Map/LF_MapShareRules.c: both run the one
// case table addons/LifeFramework/Configs/Map/Rules/shares.cases.json, so they cannot drift.
// red-proof: tools/validation/map-shares-selftest.mjs breaks a case and the table fails.
//
//   node tools/map/rules/shares.mjs          run the case table (exit 1 on a mismatch or a stale Enforce copy)
//   node tools/map/rules/shares.mjs --gen    write the Enforce copy of the table (LF_MapShareCases.generated.c)
//
// Exports
//   inAudience(audience, id, member)  member = { uid, roles, org } -> bool
//   expired(expires, now)             world seconds; expires 0 never expires -> bool
//   diff(delivered, wanted)           -> { add: [...], remove: [...] } in list order
//   evaluate(input)                   the case-table entry point -> "yes" | "no" | "add:..|remove:.."
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const rule = "shares";
export const CASES_PATH = "addons/LifeFramework/Configs/Map/Rules/shares.cases.json";
export const GENERATED_PATH = "addons/LifeFramework/Scripts/Game/Feature/Map/LF_MapShareCases.generated.c";
const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..", "..", "..");

/** Does a player receive a row? roles holds on-duty services only (D-M10). An empty id matches nobody. */
export function inAudience(audience, id = "", { uid = "", roles = [], org = "" } = {}) {
  switch (audience) {
    case "PLAYER":
      return id !== "" && id === uid;
    case "ROLE":
      return id !== "" && roles.includes(id);
    case "ORG":
      return id !== "" && id === org;
    case "EVERYONE":
      return true;
    default:
      return false;
  }
}

export function expired(expires, now) {
  return expires > 0 && now >= expires;
}

export function diff(delivered = [], wanted = []) {
  return {
    add: wanted.filter((k) => !delivered.includes(k)),
    remove: delivered.filter((k) => !wanted.includes(k)),
  };
}

export function evaluate(input) {
  if (input.op === "audience") return inAudience(input.audience, input.id, input) ? "yes" : "no";
  if (input.op === "expired") return expired(input.expires, input.now) ? "yes" : "no";
  if (input.op === "diff") {
    const d = diff(input.delivered, input.wanted);
    return `add:${d.add.join(",")}|remove:${d.remove.join(",")}`;
  }
  return `unknown op ${input.op}`;
}

export function runCases(table) {
  const fails = [];
  for (const c of table.cases ?? []) {
    const got = evaluate(c.input);
    if (got !== c.expect) fails.push(`case "${c.name}": expected ${c.expect}, got ${got}`);
  }
  return fails;
}

/** The Enforce copy of the case table (the engine cannot open an addon's loose .json). */
export function generatedSource(root = ROOT) {
  const NL = String.fromCharCode(10);
  const BS = String.fromCharCode(92);
  const TAB = String.fromCharCode(9);
  const lines = readFileSync(join(root, CASES_PATH), "utf8").split(NL);
  while (lines.length && lines[lines.length - 1] === "") lines.pop();
  const q = (s) => s.split(BS).join(BS + BS).split('"').join(BS + '"');
  return [
    "// GENERATED by tools/map/rules/shares.mjs --gen from Configs/Map/Rules/shares.cases.json. Do not edit.",
    "//! The shared-mark case table as lines, for LF_Test_MapShares (the engine cannot read the loose .json).",
    "class LF_MapShareCasesData",
    "{",
    TAB + "//------------------------------------------------------------------------------------------------",
    TAB + "static string Json()",
    TAB + "{",
    TAB + TAB + "string text;",
    ...lines.map((l) => TAB + TAB + 'text += "' + q(l) + BS + 'n";'),
    TAB + TAB + "return text;",
    TAB + "}",
    "}",
    "",
  ].join(NL);
}

export function generatedIsCurrent(root = ROOT) {
  const f = join(root, GENERATED_PATH);
  return existsSync(f) && readFileSync(f, "utf8") === generatedSource(root);
}

export function loadCases(root = ROOT) {
  return JSON.parse(readFileSync(join(root, CASES_PATH), "utf8"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--gen")) {
    writeFileSync(join(ROOT, GENERATED_PATH), generatedSource());
    console.log(`shares: wrote ${GENERATED_PATH}`);
    process.exit(0);
  }
  const table = loadCases();
  const fails = runCases(table);
  if (!generatedIsCurrent()) fails.push(`${GENERATED_PATH} is out of date: run node tools/map/rules/shares.mjs --gen`);
  for (const f of fails) console.error(`FAIL ${f}`);
  if (fails.length) process.exit(1);
  console.log(`shares: ok (${table.cases.length} cases)`);
}
