// docs/features.md is a generated index of docs/features/<area>.md. Rows live in the area files,
// so two PRs touching different areas never touch the same file. Regenerate: tools\cli regen-features.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

export const PREAMBLE = `# Life Framework — Implemented Features & Contracts

> Ground truth of what the codebase currently contains and what each system is
> supposed to do. First written from a read-only sweep of
> \`addons/LifeFramework/Scripts/Game/\` (2026-08-29); rows marked **verified
> 2026-08-30** were re-audited against current code during the P0 ship-blocker
> pass. Every claim carries a file path. This is the contract test cases must
> prove.
>
> **Keep the area files current.** The rows live in \`docs/features/<area>.md\`,
> one file per area; this file is only the generated index. Update the affected
> feature's rows in the SAME change that alters the system — a stale row reads
> as "broken" and wastes the next agent's whole session (the 2026-08-29 sweep
> claimed several already-fixed exploits were live; that gaslight is what this
> note prevents). **Never edit rows here:** the index is regenerated by
> \`tools\\cli regen-features\` and \`validate-features-index\` fails on a hand edit.
> \`tools\\cli validate\` runs \`validate-docs-sync.ps1\`, which warns when feature
> code changes without a \`docs/features/\` file changing.
>
> **Status legend per feature:** ✅ implemented (what "working" means), ⚠️
> known-fragile/untested contract, ❌ known bug or broken path.
`;

export function areaFiles(root) {
  const dir = join(root, "docs", "features");
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith(".md")).sort();
}

export function areaTitle(root, file) {
  const first = readFileSync(join(root, "docs", "features", file), "utf8").split("\n", 1)[0];
  return first.replace(/^#\s+/, "").trim() || file.replace(/\.md$/, "");
}

// extra: [{ file, title }] area files about to be written (the scaffold renders the index before they exist).
export function renderIndex(root, extra = []) {
  const known = new Set(areaFiles(root));
  const rows = areaFiles(root).map((f) => ({ file: f, title: areaTitle(root, f) }));
  for (const e of extra) if (!known.has(e.file)) rows.push(e);
  rows.sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0));
  const lines = rows.map((r) => `- [${r.title}](features/${r.file})`);
  return `${PREAMBLE}\n## Areas\n\n${lines.join("\n")}\n`;
}

export const areaPath = (slug) => `docs/features/${slug}.md`;

export function slugOf(heading) {
  return heading.replace(/\s*\([^)]*\)\s*$/, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

// Split an old-layout features.md by "## " headings. `body` is the exact area-file content:
// "# <heading>\n" plus the section text up to the next "## " (byte-preserved).
export function splitSections(text) {
  const lines = String(text).split("\n");
  const starts = [];
  lines.forEach((l, i) => { if (l.startsWith("## ")) starts.push(i); });
  return starts.map((s, k) => {
    const end = k + 1 < starts.length ? starts[k + 1] : lines.length;
    const heading = lines[s].slice(3).trim();
    return { heading, slug: slugOf(heading), body: `# ${heading}\n${lines.slice(s + 1, end).join("\n")}${end < lines.length ? "\n" : ""}` };
  });
}
