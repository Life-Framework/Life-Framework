# tools/validation/gen-test-registry.ps1 - auto-generate the LF_Test registry.
# inputs: addons/**
#
# The test registry used to be a hand-edited list inside LF_TestManager.c, which
# made it a single-writer file that parallel agents could not touch safely. This
# script derives the registry from the test files themselves, so the registry is
# machine-maintained and any agent that adds a test file just regenerates it.
#
# Contract (mirrored by validate-tests.ps1):
#   1. Every class matching `class LF_Test_\w+ : LF_Test` in the
#      top level of
#      Scripts/Game/Tests/ must declare a `// tier: LOGIC|WORLD|PERSISTENCE|PERF`
#      comment above its declaration. The tier drives which suites run it.
#   2. The generated file LF_TestRegistrations.generated.c registers every such
#      class through LF_TestManager.Register, in deterministic file order.
#   3. The generated file is never edited by hand; regenerate it instead.
#
# Modes:
#   -Write   regenerate LF_TestRegistrations.generated.c in place
#   -Check   regenerate to a string and compare with disk (exit 1 on drift)
#
# Exit codes: 0 = contract holds / written, 1 = violations or drift.

param(
  [switch]$Write,
  [switch]$Check
)

$ErrorActionPreference = "Stop"

$root = git rev-parse --show-toplevel
if (-not $root) { Write-Host "ERROR not a git work tree"; exit 1 }

$testsDir = Join-Path $root "addons\LifeFramework\Scripts\Game\Tests"
$generatedPath = Join-Path $testsDir "LF_TestRegistrations.generated.c"
$generatedName = "LF_TestRegistrations.generated.c"

$entries = @()
$violations = @()

Get-ChildItem $testsDir -Filter "*.c" | Where-Object { $_.Name -ne $generatedName } | Sort-Object Name | ForEach-Object {
  $file = $_
  $text = Get-Content $file.FullName -Raw

  $matches = [regex]::Matches($text, 'class\s+(LF_Test_\w+)\s*:\s*LF_Test')
  foreach ($m in $matches) {
    $cls = $m.Groups[1].Value

    $segment = $text.Substring(0, $m.Index)
    $tierMatch = [regex]::Matches($segment, '//\s*tier:\s*(LOGIC|WORLD|PERSISTENCE|PERF)')
    if ($tierMatch.Count -eq 0) {
      $violations += "$($file.Name): class $cls has no '// tier:' comment above its declaration"
      continue
    }

    $tier = $tierMatch[$tierMatch.Count - 1].Groups[1].Value
    $entries += [PSCustomObject]@{ File = $file.Name; Class = $cls; Tier = $tier }
  }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// GENERATED FILE - do not edit by hand.")
[void]$sb.AppendLine("// Regenerated by 'tools\cli regen-tests' and checked by 'tools\cli validate'.")
[void]$sb.AppendLine("// Every test class declares its tier with a '// tier:' comment above its declaration;")
[void]$sb.AppendLine("// this registry is derived from those files in deterministic order.")
[void]$sb.AppendLine("class LF_TestRegistrations")
[void]$sb.AppendLine("{")
[void]$sb.AppendLine("`tstatic void RegisterAll(LF_TestManager manager)")
[void]$sb.AppendLine("`t{")
foreach ($e in $entries) {
  [void]$sb.AppendLine("`t`tmanager.Register(new $($e.Class)(), LF_TestTier.$($e.Tier));")
}
[void]$sb.AppendLine("`t}")
[void]$sb.AppendLine("}")
[void]$sb.AppendLine("")

# LF on every platform (AppendLine uses the OS newline); .gitattributes pins LF.
$generated = $sb.ToString() -replace "`r`n", "`n"

# Pack tests (docs/architecture/three-worlds.md "Pack test leg"): each pack's Scripts/Game/Tests holds
# LF_Test_* files of its own. They are registered by a generated file in the pack, a modded
# LF_TestManager that overrides RegisterPackTests, so the core registry above never names a pack class
# (validate-addon-boundary). The runner skips a pack test unless it is named; `tools\cli test` names
# them in the pack leg, which boots under the pack's mission header.
$packGeneratedName = "LF_PackTestRegistrations.generated.c"
$packOut = @()
$coreClasses = @{}
foreach ($e in $entries) { $coreClasses[$e.Class] = $true }
Get-ChildItem (Join-Path $root "addons") -Directory | Where-Object { $_.Name -like "LF_*" } | Sort-Object Name | ForEach-Object {
  $packName = $_.Name
  $packTests = Join-Path $_.FullName "Scripts\Game\Tests"
  $packPath = Join-Path $packTests $packGeneratedName
  $packEntries = @()
  if (Test-Path -LiteralPath $packTests) {
    Get-ChildItem $packTests -Filter "*.c" | Where-Object { $_.Name -ne $packGeneratedName } | Sort-Object Name | ForEach-Object {
      $file = $_
      $text = Get-Content $file.FullName -Raw
      foreach ($m in [regex]::Matches($text, 'class\s+(LF_Test_\w+)\s*:\s*LF_Test')) {
        $cls = $m.Groups[1].Value
        $tierMatch = [regex]::Matches($text.Substring(0, $m.Index), '//\s*tier:\s*(LOGIC|WORLD|PERSISTENCE|PERF)')
        if ($tierMatch.Count -eq 0) {
          $violations += "$($file.Name): class $cls has no '// tier:' comment above its declaration"
          continue
        }
        if ($coreClasses.ContainsKey($cls)) {
          $violations += "$($file.Name): pack test $cls has the name of a core test"
          continue
        }
        $packEntries += [PSCustomObject]@{ Class = $cls; Tier = $tierMatch[$tierMatch.Count - 1].Groups[1].Value }
      }
    }
  }
  $text = $null
  if ($packEntries.Count -gt 0) {
    $pb = New-Object System.Text.StringBuilder
    [void]$pb.AppendLine("// GENERATED FILE - do not edit by hand.")
    [void]$pb.AppendLine("// Regenerated by 'tools\cli regen-tests' and checked by 'tools\cli validate'.")
    [void]$pb.AppendLine("// The pack's tests: they run only when named, in the pack leg of 'tools\cli test'.")
    [void]$pb.AppendLine("modded class LF_TestManager")
    [void]$pb.AppendLine("{")
    [void]$pb.AppendLine("`tprotected override void RegisterPackTests()")
    [void]$pb.AppendLine("`t{")
    [void]$pb.AppendLine("`t`tsuper.RegisterPackTests();")
    foreach ($e in $packEntries) {
      [void]$pb.AppendLine("`t`tRegisterPack(new $($e.Class)(), LF_TestTier.$($e.Tier));")
    }
    [void]$pb.AppendLine("`t}")
    [void]$pb.AppendLine("}")
    [void]$pb.AppendLine("")
    $text = $pb.ToString() -replace "`r`n", "`n"
  }
  $packOut += [PSCustomObject]@{ Pack = $packName; Path = $packPath; Text = $text; Count = $packEntries.Count }
}

if ($violations.Count -gt 0) {
  Write-Host "gen-test-registry: FAILED ($($violations.Count) violation(s))"
  foreach ($v in $violations) { Write-Host "  - $v" }
  exit 1
}

if ($Write) {
  Set-Content -LiteralPath $generatedPath -Value $generated -NoNewline
  Write-Host "gen-test-registry: OK ($($entries.Count) test class(es) -> $generatedName)"
  foreach ($p in $packOut) {
    if ($p.Text) {
      Set-Content -LiteralPath $p.Path -Value $p.Text -NoNewline
      Write-Host "gen-test-registry: OK ($($p.Count) pack test class(es) -> $($p.Pack)/Scripts/Game/Tests/$packGeneratedName)"
    } elseif (Test-Path -LiteralPath $p.Path) {
      Remove-Item -LiteralPath $p.Path
      Write-Host "gen-test-registry: removed $($p.Pack)/Scripts/Game/Tests/$packGeneratedName (no pack tests left)"
    }
  }
  exit 0
}

# No flag (e.g. bare run by `cli validate`) means check mode: the generated
# registry must be in sync with the test files.
if ($Check -or -not $Write) {
  if (-not (Test-Path -LiteralPath $generatedPath)) {
    Write-Host "gen-test-registry: FAILED - $generatedName missing (run 'tools\cli regen-tests')"
    exit 1
  }
  $onDisk = Get-Content -LiteralPath $generatedPath -Raw
  if (($onDisk -replace "`r`n", "`n") -ne $generated) {
    Write-Host "gen-test-registry: FAILED - $generatedName out of sync with the test files (run 'tools\cli regen-tests')"
    exit 1
  }
  foreach ($p in $packOut) {
    $exists = Test-Path -LiteralPath $p.Path
    $drift = $false
    if ($p.Text) { $drift = -not $exists -or (((Get-Content -LiteralPath $p.Path -Raw) -replace "`r`n", "`n") -ne $p.Text) }
    elseif ($exists) { $drift = $true }
    if ($drift) {
      Write-Host "gen-test-registry: FAILED - $($p.Pack)/Scripts/Game/Tests/$packGeneratedName out of sync with the pack tests (run 'tools\cli regen-tests')"
      exit 1
    }
  }
  Write-Host "gen-test-registry: OK ($($entries.Count) test class(es) registered, registry in sync)"
  exit 0
}

Write-Host "gen-test-registry: specify -Write or -Check"
exit 2