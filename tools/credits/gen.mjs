// In-game credits from the one credits source (#481).
//
// docs/credits.md is what the website /credits page and the README are built from. This reads the
// same file and writes what the game shows on the credits notice:
//   - one string-table row per section heading and per credit line, keyed by a hash of its text
//     (LF-Credits_H_<hash>, LF-Credits_R_<hash>), appended to the string table. A changed line gets
//     a new key; nothing in the table is rewritten.
//   - Scripts/Game/Feature/Signs/LF_CreditsRows.generated.c, the ordered list of those keys.
//
// What becomes a line: every data row of a table (first cell, then the second: who or what made it)
// and every bullet that starts with a link (a project or a tool). File paths, URLs and markdown are
// dropped; the card ends with a pointer to the full page.
//
//   node tools/credits/gen.mjs --write     regenerate (then tools\cli regen-localization)
//   node tools/credits/gen.mjs --check     exit 1 when the game's list is out of date
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const SOURCE = "docs/credits.md";
export const ST = "addons/LifeFramework/Language/everonlife_localization.st";
export const OUT = "addons/LifeFramework/Scripts/Game/Feature/Signs/LF_CreditsRows.generated.c";

// Markdown to the plain text a printed notice carries.
export function plain(md) {
  let s = String(md);
  s = s.replace(/\[([^\]]+)\]\([^)]*\)/g, "$1"); // links keep their text
  s = s.replace(/\s*\([^()]*`[^()]*\)/g, ""); // "(`path/in/repo`)" is for maintainers
  s = s.replace(/`([^`]*)`/g, "$1");
  s = s.replace(/\s*\(?https?:\/\/[^\s)|]+\)?/g, "");
  s = s.replace(/\*\*([^*]+)\*\*/g, "$1").replace(/\*/g, "");
  s = s.replace(/\s*\(see [^()]*\)/gi, ""); // "(see Voice-over below)" points inside the document
  s = s.replace(/"/g, "'").replace(/[<>]/g, "");
  return s.replace(/\s+/g, " ").trim();
}

function firstSentence(s) {
  const m = /^(.*?[.!?])(\s|$)/.exec(s);
  return (m ? m[1] : s).trim();
}

function cells(line) {
  return line.trim().replace(/^\|/, "").replace(/\|$/, "").split("|").map((c) => c.trim());
}

// [{ kind: "H" | "R", text }] in display order. A section with no credit line is left out.
export function parse(md) {
  const out = [];
  let heading = null;
  let pending = [];
  const flush = () => {
    if (heading && pending.length) out.push({ kind: "H", text: heading }, ...pending.map((text) => ({ kind: "R", text })));
    pending = [];
  };
  let inFence = false;
  let tableRow = 0;
  for (const raw of String(md).replace(/\r\n/g, "\n").split("\n")) {
    if (raw.startsWith("```")) inFence = !inFence;
    if (inFence) continue;
    const h = /^##\s+(.+)$/.exec(raw);
    if (h) {
      flush();
      heading = plain(h[1]).replace(/\s*\(.*\)$/, "");
      tableRow = 0;
      continue;
    }
    if (raw.startsWith("|")) {
      tableRow++;
      if (tableRow <= 2) continue; // header and rule
      const c = cells(raw);
      const what = plain(c[0]).split(": ")[0].replace(/\.$/, "");
      const who = firstSentence(plain(c[1] ?? "")).replace(/\.$/, "");
      if (what) pending.push(who && who !== what ? `${what}. ${who}.` : `${what}.`);
      continue;
    }
    tableRow = 0;
    const b = /^- (\[.+)$/.exec(raw);
    if (b) pending.push(firstSentence(plain(b[1])).replace(/([^.!?])$/, "$1."));
  }
  flush();
  return out;
}

export function keyOf(row) {
  const hash = createHash("sha1").update(`${row.kind}:${row.text}`).digest("hex").slice(0, 8).toUpperCase();
  return `LF-Credits_${row.kind}_${hash}`;
}

function guidOf(key) {
  return createHash("sha1").update(`credits-guid:${key}`).digest("hex").slice(0, 16).toUpperCase();
}

export function stItem(row) {
  const key = keyOf(row);
  const comment = row.kind === "H" ? "Credits notice: a section heading. Generated from docs/credits.md (tools/credits/gen.mjs)." : "Credits notice: one credit. Generated from docs/credits.md (tools/credits/gen.mjs).";
  return [`    CustomStringTableItem "{${guidOf(key)}}" {`, `     Id "${key}"`, `     Target_en_us "${row.text}"`, `     Comment "${comment}"`, "    }"].join("\n");
}

// The string table with the missing rows appended before its closing braces.
export function withRows(st, rows) {
  const missing = rows.filter((r) => !st.includes(`Id "${keyOf(r)}"`));
  if (!missing.length) return st;
  const marker = "\n  }\n }\n}";
  const at = st.lastIndexOf(marker);
  if (at === -1) throw new Error("string table: closing braces not found");
  return `${st.slice(0, at)}\n${missing.map(stItem).join("\n")}${st.slice(at)}`;
}

export function script(rows) {
  const lines = rows.map((r) => `\t\tkinds.Insert("${r.kind}");\n\t\tkeys.Insert("#${keyOf(r)}");`);
  return `// Generated by tools/credits/gen.mjs from docs/credits.md. Do not edit: change the source and run
// \`node tools/credits/gen.mjs --write\`. validate-credits fails when this file is out of date.
class LF_CreditsRows
{
	static const int COUNT = ${rows.length};

	//------------------------------------------------------------------------------------------------
	//! The credits in display order: kinds[i] is "H" (a section heading) or "R" (one credit),
	//! keys[i] is its string key.
	static void Fill(notnull array<string> kinds, notnull array<string> keys)
	{
${lines.join("\n")}
	}
}
`;
}

export function problems(root) {
  const rows = parse(readFileSync(join(root, SOURCE), "utf8"));
  const out = [];
  if (rows.length < 4) out.push(`${SOURCE} yields only ${rows.length} credit line(s); the parser no longer matches the file`);
  const have = existsSync(join(root, OUT)) ? readFileSync(join(root, OUT), "utf8").replace(/\r\n/g, "\n") : "";
  if (have !== script(rows)) out.push(`${OUT} is out of date with ${SOURCE}: run node tools/credits/gen.mjs --write, then tools\\cli regen-localization`);
  const st = readFileSync(join(root, ST), "utf8");
  for (const r of rows) {
    if (!st.includes(`Id "${keyOf(r)}"`)) out.push(`the string table has no ${keyOf(r)} ("${r.text.slice(0, 50)}"): run node tools/credits/gen.mjs --write`);
  }
  for (const r of rows) {
    if (r.text.length > 160) out.push(`a credit line is ${r.text.length} characters ("${r.text.slice(0, 50)}..."); keep the first two cells of the row short`);
  }
  return out;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
  if (process.argv.includes("--write")) {
    const rows = parse(readFileSync(join(root, SOURCE), "utf8"));
    writeFileSync(join(root, OUT), script(rows));
    const st = readFileSync(join(root, ST), "utf8");
    const next = withRows(st, rows);
    if (next !== st) writeFileSync(join(root, ST), next);
    console.log(`credits: ${rows.filter((r) => r.kind === "R").length} credit(s) in ${rows.filter((r) => r.kind === "H").length} section(s) written`);
    for (const r of rows) console.log(`  ${r.kind} ${r.text}`);
    process.exit(0);
  }
  const bad = problems(root);
  if (bad.length) {
    console.log("validate-credits: FAIL");
    for (const b of bad) console.log(`  ${b}`);
    process.exit(1);
  }
  console.log("validate-credits: OK (the in-game credits match docs/credits.md)");
}
