// tools/buildings/pipeline/store-slots.mjs - the `store` stage of tools\cli building (#1143).
//
// A building whose spec has a `store` block becomes one of our physical stores (Feature/Shop): a
// prefab inheriting the generated building, with LF_ShopComponent (prices), LF_StoreComponent (stock,
// shelf points, boundary) and a "Pay for goods" till context at every cash register the export placed.
// The furniture prefab sits at the building origin, so a fixture child's coords are store-local and
// each shelf point is the fixture's position plus a board point turned by its yaw. Boards and the goods'
// footprints come from fixtures.json, generated by `tools\cli fixtures` from the models (#1143): a
// board is filled with as many of the item as its width takes, one or two rows by its depth. The whole
// prefab is written from the spec on every run: rebuilding the building regenerates the slots.
//
// spec.store: {
//   "prefab": "Supermarket_Store",             file name in prefab_dir (default <name>_Store)
//   "key": "everon_supermarket",                LF_StoreComponent.m_sStoreKey, unique in the world
//   "boundary": { "center": [x, y, z], "half": [x, 0, z] },   leaving it unpaid is shoplifting
//   "restock_seconds": 120,
//   "till": "CashierShop_01",                   the vanilla prop that is a till
//   "lines": [ { "item": "{GUID}Prefabs/...et", "fixture": "ShelfShop_01", "pick": [0, 2], "boards": [2] } ]
// }
// `pick` indexes the fixtures of that prefab in the order the stage prints (by x, then z, then yaw);
// `boards` indexes their boards, lowest first (the stage prints those too). Optional per line:
// `per_board` (at most this many copies on a board), `rows`, `max` (default: one per shelf point),
// `restock` (default: a sixth of max), `start`.
//
// A building made from a vanilla one (spec.vanilla, no ArchBuilder export) has no shop furniture of its
// own, so the store block places it, and two more kinds of row exist (gun store, #1143 follow-up):
//   "fixtures": [ { "prefab": "{GUID}Prefabs/...et", "at": [x, y, z], "yaw": 90, "why": "..." } ]
//       children of the store prefab; `pick` counts them with the furniture prefab's own.
//   a line with "display": true stands its item in a display rack's slots (fixtures.json `racks`, read
//       from the vanilla arsenal rack): { "item", "display": true, "fixture": "LF_WeaponRackCabinet_Display",
//       "pick": [0], "kind": "long", "slots": [0, 1] }. The copy is the item's model on a plain entity:
//       it can be looked at, never picked up or taken, and it is no stock (the counter sells it).
//   "counters": [ { "prefab": "{GUID}...et with LF_ShopComponent", "at", "yaw", "outlet": "gun_counter" } ]
//       a counter child whose LF_ShopComponent sells that item catalogue outlet over the counter, behind
//       the outlet's gates (FIREARM_PERMIT on the gun counter). The outlet must have offers.
