// tools/grid/cell-index.mjs - the grid's visual index: docs/architecture/grid-cells.md, one picture per claimed cell.
//   node tools/grid/cell-index.mjs            rewrite the doc from tools/grid/cells/*.json and the pictures kept for #1802
//   node tools/grid/cell-index.mjs --check    exit 1 when the doc is stale or a claimed cell has no picture (a note, not a gate)
// The pictures are `tools\cli look grid:all --close 0` kept with `tools\cli evidence 1802 after grid-<slug>`
// (website/public/docs-images/1802/grid-<slug>-after.png); a cell added later runs `look grid:<slug>` and `evidence` the same way.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { readCells } from "../lib/world-zones.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const DOC = "docs/architecture/grid-cells.md";
const KEY = "1802";
const IMG = `website/public/docs-images/${KEY}`;
const RAW = "https://raw.githubusercontent.com/Life-Framework/Life-Framework/main/";

// Pure: the doc text for the claimed cells ({ slug, cell, span }) and the picture file names present.
export function render(cells, files) {
  const have = new Set(files);
  const rows = cells.filter((c) => c.slug && !c.error);
  const lines = [
    "# The grid, cell by cell",
    "",
    "Every claimed cell of GridWorld (`tools/grid/cells/<slug>.json`), pictured from the side players approach (`tools\\cli look grid:<slug>`).",
    "Generated by `node tools/grid/cell-index.mjs`; do not edit by hand. A new cell: `look grid:<slug>`, then `tools\\cli evidence 1802 after grid-<slug>`, then rerun the generator.",
    "The grid passes `audit placement --grid --strict` (on the ground, reachable); `wt gate` and `ci` run it when a GridWorld layer or a prefab changes, and the main guard runs it after every merge.",
    "",
    `${rows.length} cells.`,
    "",
  ];
  for (const c of rows) {
    const file = `grid-${c.slug}-after.png`;
    lines.push(`## ${c.slug}`, "", `Cell ${c.cell}${c.span ? `, ${c.span.join(" x ")} cells` : ""}; layer \`${c.layer ?? `Grid_${c.slug}.layer`}\`.`, "");
    lines.push(have.has(file) ? `![${c.slug}](${RAW}${IMG}/${file})` : `(no picture yet: \`tools\\cli look grid:${c.slug}\`, then \`tools\\cli evidence ${KEY} after grid-${c.slug}\`)`, "");
    const inside = `grid-${c.slug}-inside-after.png`;
    if (have.has(inside)) lines.push(`Inside:`, "", `![${c.slug} inside](${RAW}${IMG}/${inside})`, "");
  }
  return lines.join("\n");
}

export function main(argv = process.argv.slice(2)) {
  const dir = join(ROOT, IMG);
  const files = existsSync(dir) ? readdirSync(dir) : [];
  const text = render(readCells(ROOT), files);
  const missing = readCells(ROOT).filter((c) => c.slug && !files.includes(`grid-${c.slug}-after.png`)).map((c) => c.slug);
  if (argv.includes("--check")) {
    const stale = !existsSync(join(ROOT, DOC)) || readFileSync(join(ROOT, DOC), "utf8") !== text;
    if (missing.length) console.log(`grid-cells: no picture for ${missing.join(", ")}`);
    if (stale) console.log(`grid-cells: ${DOC} is stale; run node tools/grid/cell-index.mjs`);
    return stale || missing.length ? 1 : 0;
  }
  writeFileSync(join(ROOT, DOC), text);
  console.log(`grid-cells: ${DOC} written, ${readCells(ROOT).length} cell(s), ${missing.length} without a picture`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main());
