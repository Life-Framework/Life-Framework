// Builds the outreach screenshot and GIF set (#570) from content/outreach-media.json into
// public/outreach/: 16:9 and 9:16 JPEGs of each still, slideshow GIFs, index.json and a readable index.
// The output is committed, so a post can use it without a build. Run from website/:
//   node scripts/outreach-media.mjs
// The GIFs need sharp 0.34 or newer (`npm i --no-save sharp@0.34.5`); with an older sharp the stills are
// still written and the GIFs are skipped.
//
// 16:9: the capture at 1280x720. 9:16: a vertical crop of the same frame around `focusX` (0 left, 1 right,
// default centre), 576x1024. Nothing is added to a frame.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = (id) => path.join(site, "public", "docs-images", `${id}.png`);
const outDir = path.join(site, "public", "outreach");
const def = JSON.parse(fs.readFileSync(path.join(site, "content", "outreach-media.json"), "utf8"));
const gallery = JSON.parse(fs.readFileSync(path.join(site, "content", "gallery.json"), "utf8"));
const captions = new Map(gallery.featured.map((f) => [f.id, f.caption]));

for (const d of ["16x9", "9x16", "gif"]) fs.mkdirSync(path.join(outDir, d), { recursive: true });
const rel = (p) => path.relative(outDir, p).split(path.sep).join("/");

const stills = [];
for (const s of def.stills) {
  if (!fs.existsSync(src(s.src))) throw new Error(`missing capture ${s.src}`);
  const caption = s.caption ?? captions.get(s.src);
  if (!caption) throw new Error(`${s.src} has no caption: add it to content/gallery.json featured or give "caption" here`);
  const wide = path.join(outDir, "16x9", `${s.slug}.jpg`);
  const tall = path.join(outDir, "9x16", `${s.slug}.jpg`);
  const img = sharp(src(s.src));
  const meta = await img.metadata();
  await img.clone().resize(1280, 720, { fit: "cover" }).jpeg({ quality: 82, mozjpeg: true }).toFile(wide);
  const cropW = Math.round((meta.height * 9) / 16);
  const left = Math.max(0, Math.min(meta.width - cropW, Math.round((s.focusX ?? 0.5) * meta.width - cropW / 2)));
  await sharp(src(s.src)).extract({ left, top: 0, width: cropW, height: meta.height }).resize(576, 1024).jpeg({ quality: 84, mozjpeg: true }).toFile(tall);
  stills.push({ slug: s.slug, source: `docs-images/${s.src}.png`, caption, alt: caption, wide: rel(wide), tall: rel(tall), bytesWide: fs.statSync(wide).size, bytesTall: fs.statSync(tall).size });
}

const major = Number(sharp.versions.sharp.split(".")[0]);
const minor = Number(sharp.versions.sharp.split(".")[1]);
const canJoin = major > 0 || minor >= 34;
const gifs = [];
if (!canJoin) console.warn(`[outreach-media] sharp ${sharp.versions.sharp} cannot join frames; GIFs skipped (need 0.34+)`);
for (const g of canJoin ? def.slideshows : []) {
  const frames = await Promise.all(g.frames.map((id) => sharp(src(id)).resize(640, 360, { fit: "cover" }).png().toBuffer()));
  const file = path.join(outDir, "gif", `${g.slug}.gif`);
  await sharp(frames, { join: { animated: true } })
    .gif({ delay: frames.map(() => 1800), loop: 0, effort: 7, colours: 160 })
    .toFile(file);
  gifs.push({ slug: g.slug, title: g.title, caption: g.caption, alt: g.caption, file: rel(file), frames: g.frames.length, bytes: fs.statSync(file).size });
}

fs.writeFileSync(path.join(outDir, "index.json"), JSON.stringify({ credit: def.credit, stills, gifs, clipsToCapture: def.clipsToCapture }, null, 2) + "\n");

const kb = (n) => `${Math.round(n / 1024)} KB`;
const md = [];
md.push("# Outreach screenshots and GIFs", "");
md.push("Generated by `website/scripts/outreach-media.mjs` from `website/content/outreach-media.json`. Do not edit by hand.", "");
md.push(`**Credit line, put it in a post when base-game assets show (they always do):** ${def.credit}`, "");
md.push("On the site these are at `https://life-framework.org/outreach/<path>`. In a post, attach the file; do not hotlink.", "");
md.push("## Screenshots", "");
md.push("16:9 is 1280x720, for Reddit, Discord, the Workshop and the forums. 9:16 is 576x1024, a vertical crop of the same frame, for stories and shorts. The caption is also the alt text.", "");
md.push("| Picture | 16:9 | 9:16 | Caption and alt text |", "| --- | --- | --- | --- |");
for (const s of stills) md.push(`| ${s.slug} | [${kb(s.bytesWide)}](${s.wide}) | [${kb(s.bytesTall)}](${s.tall}) | ${s.caption} |`);
md.push("", "## GIFs", "");
md.push("Slideshows of the stills above, 640x360, about 1.8 s a frame. They are not footage. Real motion clips are listed under \"Clips still to capture\"; there is no 9:16 GIF yet.", "");
md.push("| GIF | Frames | Size | Caption and alt text |", "| --- | --- | --- | --- |");
for (const g of gifs) md.push(`| [${g.slug}](${g.file}) | ${g.frames} | ${kb(g.bytes)} | ${g.caption} |`);
md.push("", "## Clips still to capture", "");
md.push("These need a game session (`tools\\cli session up`, then the film pipeline). They are the first things to record for real GIFs and the hero video (#571).", "");
md.push("| Clip | Length | Shows |", "| --- | --- | --- |");
for (const c of def.clipsToCapture) md.push(`| ${c.slug} | ${c.length} | ${c.shows} |`);
md.push("");
fs.writeFileSync(path.join(outDir, "README.md"), md.join("\n"));
console.log(`[outreach-media] ${stills.length} stills, ${gifs.length} GIFs -> public/outreach/`);
